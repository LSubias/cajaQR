BEGIN;
CREATE SCHEMA IF NOT EXISTS cajaqr;
REVOKE ALL ON SCHEMA cajaqr FROM PUBLIC;

CREATE TABLE IF NOT EXISTS cajaqr.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    unit BIGINT NOT NULL,
    stock INTEGER NOT NULL CHECK (stock >= 0),
    size TEXT NOT NULL DEFAULT '',
    image TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS cajaqr.categories (
    name TEXT NOT NULL UNIQUE,
    normalized_name TEXT PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS cajaqr.users (
    username TEXT PRIMARY KEY,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'seller'))
);
CREATE TABLE IF NOT EXISTS cajaqr.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token TEXT NOT NULL UNIQUE,
    items TEXT NOT NULL,
    total BIGINT NOT NULL,
    receipt BYTEA,
    delivered SMALLINT NOT NULL DEFAULT 0,
    verified SMALLINT NOT NULL DEFAULT 0,
    canceled SMALLINT NOT NULL DEFAULT 0,
    seller TEXT,
    sold_on TEXT
);
CREATE INDEX IF NOT EXISTS sales_by_seller ON cajaqr.sales (seller, id DESC) WHERE canceled = 0;

INSERT INTO cajaqr.categories(name, normalized_name)
VALUES ('Pantalones', 'pantalones'), ('Remeras', 'remeras'), ('Zapatillas', 'zapatillas')
ON CONFLICT DO NOTHING;
COMMIT;
